#!/usr/bin/env node
// Build the result view (ui/result) into one HTML file with the script and
// styles inline, and write it to src/ui/resultHtml.generated.ts for the server.
// Runs before tsc, typecheck and the tests. The output is not committed.
//
//   node scripts/build-ui.mjs           build
//   node scripts/build-ui.mjs --html F  also write the HTML to F, for a preview

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, transform } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'ui', 'result');
const output = join(root, 'src', 'ui', 'resultHtml.generated.ts');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const bundled = await build({
  entryPoints: [join(source, 'main.ts')],
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  write: false,
  legalComments: 'none',
  define: { __APP_VERSION__: JSON.stringify(version) },
  logLevel: 'warning',
});
const script = bundled.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const styles = (await transform(readFileSync(join(source, 'styles.css'), 'utf8'), { loader: 'css', minify: true })).code;

const html = readFileSync(join(source, 'index.html'), 'utf8')
  .replace('/*STYLES*/', () => styles.trim())
  .replace('/*SCRIPT*/', () => script.trim());

const module = `// Generated by scripts/build-ui.mjs from ui/result. Do not edit.\nexport const RESULT_VIEW_HTML = ${JSON.stringify(html)};\n`;
if (!existsSync(output) || readFileSync(output, 'utf8') !== module) {
  writeFileSync(output, module);
}

const htmlFlag = process.argv.indexOf('--html');
if (htmlFlag !== -1 && process.argv[htmlFlag + 1]) {
  writeFileSync(process.argv[htmlFlag + 1], html);
}

console.log(`result view: ${(Buffer.byteLength(html) / 1024).toFixed(0)} KB`);
